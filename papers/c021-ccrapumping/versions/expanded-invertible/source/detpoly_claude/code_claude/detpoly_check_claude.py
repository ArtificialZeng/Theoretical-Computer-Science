# ------------------------------------------------------------------ helpers
def mexp(X):
    n = X.nrows(); R = eye(n); T = eye(n)
    for k in range(1, n + 1):
        T = T * X * Q(1, k)
        if is_zero_mat(T):
            break
        R += T
    return R

def mlog(U):
    return mlog_unip(U)

def polyval(p, X):
    n = X.nrows(); R = zeros(n, n)
    for c in reversed(p.coeffs()):
        R = R * X + eye(n) * c
    return R

def jordan_s(X):
    """semisimple part of a rational matrix (Newton iteration on the squarefree part)."""
    cp = X.charpoly()
    cpq = flint.fmpq_poly([Q(c) for c in cp.coeffs()])
    q = cpq / cpq.gcd(cpq.derivative())
    dq = q.derivative()
    s = X
    for _ in range(64):
        qs = polyval(q, s)
        if is_zero_mat(qs):
            return s
        s = s - qs * polyval(dq, s).inv()
    raise RuntimeError("Newton did not converge")

def maxbits(mats):
    return max([mat_bits(X) for X in mats] + [0])

def subspace_bits(S):
    return max([vec_bits(b) for b in S.basis] + [0])

# ------------------------------------------------------------------ the construction
class Detpoly:
    def __init__(self, gens):
        S = self.S = Setup(gens)
        ok, info = a_test(S, random.Random(7))
        assert ok, "(a) fails"
        self.info = info
        d = self.d = S.d
        # primitive idempotents of C = Q[S]
        Cm = info['_C']
        rng = random.Random(3)
        while True:
            c = sum((Cm[i] * Q(rng.randint(-50, 50)) for i in range(len(Cm))), zeros(d, d))
            mp = c.minpoly()
            roots = [r for r, e in mp.factor()[1]] if False else None
            fac = mp.factor()[1]
            if all(p.degree() == 1 for p, e in fac) and len(fac) == len(Cm):
                break
        eig = [-p.coeffs()[0] / p.coeffs()[1] for p, e in fac]
        idem = []
        for i, lam in enumerate(eig):
            E = eye(d)
            for j, mu in enumerate(eig):
                if j != i:
                    E = E * (c - eye(d) * mu) * (ONE / (lam - mu))
            idem.append(E)
        # weight-refined adapted basis (block diagonal change of basis)
        cols, lab, blk = [], [], []
        for p in range(S.m):
            idx = [i for i in range(d) if S.blk[i] == p]
            for wi, E in enumerate(idem):
                vs = []
                for i in idx:
                    vs.append([E[r, i] for r in range(d)])
                W = Subspace(vs, d)
                for b in W.basis:
                    cols.append(b); lab.append(wi); blk.append(p)
        Qw = flint.fmpq_mat(d, d, [cols[j][i] for i in range(d) for j in range(d)])
        self.Qw = Qw
        Qwi = Qw.inv()
        self.lab, self.blk = lab, blk
        self.nlab = len(idem)
        self.M = [Qwi * g * Qw for g in S.gens]
        self.b = [self.bpart(g) for g in self.M]
        self.ad_to_orig = Qw   # coordinates: orig_adapted = Qw * ours * Qw^{-1}

    def bpart(self, X):
        d = self.d
        return flint.fmpq_mat(d, d, [X[r, c] if self.blk[r] == self.blk[c] else ZERO
                                     for r in range(d) for c in range(d)])

    def in_uP(self, r, c):
        return self.blk[c] > self.blk[r]

    def diag_of_labels(self, y):
        d = self.d
        D = zeros(d, d)
        for i in range(d):
            D[i, i] = y[self.lab[i]]
        return D

    def label_values(self, t):
        """t in C^x (scalar lam_chi on V_chi): return lam as list over labels."""
        lam = [None] * self.nlab
        for i in range(self.d):
            if lam[self.lab[i]] is None:
                lam[self.lab[i]] = t[i, i]
        return lam

    def lie_torus_of(self, t):
        """Lie(closure<t>^o) for t in C^x, as list of label vectors (columns of valuation matrix)."""
        lam = self.label_values(t)
        primes = set()
        for x in lam:
            for z in (x.p, x.q):
                z = abs(int(z))
                if z > 1:
                    for pr, e in flint.fmpz(z).factor():
                        primes.add(int(pr))
        cols = []
        for pr in sorted(primes):
            col = []
            for x in lam:
                v = 0
                for z, sgn in ((int(x.p), 1), (int(x.q), -1)):
                    z = abs(z)
                    while z % pr == 0:
                        z //= pr; v += sgn
                col.append(Q(v))
            cols.append(col)
        return cols

    def in_C(self, X):
        d = self.d
        for r in range(d):
            for c in range(d):
                if r != c and X[r, c] != 0:
                    return False
                if self.lab[r] == self.lab[c] and X[r, r] != X[c, c]:
                    return False
        return True

    def power_into_C(self, h, limit=5000):
        P = h
        for n in range(1, limit):
            if self.in_C(P):
                return P, n
            P = P * h
        raise RuntimeError("no power in C found")

    # ---- (T1)
    def words(self, L):
        k = len(self.M)
        letters = [(a, 1) for a in range(k)] + [(a, -1) for a in range(k)]
        out = [()]
        frontier = [()]
        for _ in range(L):
            new = []
            for w in frontier:
                for l in letters:
                    if w and w[-1][0] == l[0] and w[-1][1] == -l[1]:
                        continue
                    new.append(w + (l,))
            out += new
            frontier = new
        return out

    def word_mat(self, w, mats):
        X = eye(self.d)
        for a, e in w:
            X = X * (mats[a] if e == 1 else mats[a].inv())
        return X

    def lieS_from_words(self, L):
        vecs = []
        per = {}
        for w in self.words(L):
            if not w:
                continue
            h = self.word_mat(w, self.b)
            t, n = self.power_into_C(h)
            cols = self.lie_torus_of(t)
            if cols:
                per[w] = cols
                vecs += cols
        return Subspace(vecs, self.nlab), per

    def lieS_groundtruth(self):
        """Lie(S) from Schreier generators of the kernel of the action on B (exponential)."""
        S, d = self.S, self.d
        B = Subspace([vec(self.Qw.inv() * X * self.Qw) for X in self.info['_B']], d * d)
        acts = []
        for bb in self.b:
            bi = bb.inv()
            Bm = [unvec(v, d, d) for v in B.basis]
            cl = [B.coords(vec(bb * X * bi)) for X in Bm]
            kk = B.dim
            acts.append(flint.fmpq_mat(kk, kk, [cl[j][i] for i in range(kk) for j in range(kk)]))
        sg, order = schreier(acts, self.b)
        vecs = []
        for s in sg:
            assert self.in_C(s)
            vecs += self.lie_torus_of(s)
        return Subspace(vecs, self.nlab), order

    # ---- (T2)-(T5)
    def torus_conjugator(self, per, LieS):
        d = self.d
        # pairs of distinct labels occurring in u_P
        pairs = set()
        for r in range(d):
            for c in range(d):
                if self.in_uP(r, c) and self.lab[r] != self.lab[c]:
                    pairs.add((self.lab[r], self.lab[c]))
        gens_X = []   # (X in Lie(Theta_g), b(X) label vector)
        for w, cols in per.items():
            g = self.word_mat(w, self.M)
            bg = self.bpart(g)
            if getattr(self, 'iterative', False):
                v = self.group_iter(bg, g)
            else:
                gs = jordan_s(g)
                v = self.solve_conj(bg, gs)
            vi = v.inv()
            for col in cols:
                Yd = self.diag_of_labels(col)
                gens_X.append((v * Yd * vi, col))
        rng = random.Random(11)
        for attempt in range(200):
            cs = [Q(rng.randint(0, d * d)) for _ in gens_X]
            y = [sum((c * col[i] for c, (_, col) in zip(cs, gens_X)), ZERO) for i in range(self.nlab)]
            if all(y[p] != y[q] for p, q in pairs):
                break
        else:
            raise RuntimeError("no regular element found")
        X = sum((c * Xm for c, (Xm, _) in zip(cs, gens_X)), zeros(d, d))
        Y = self.diag_of_labels(y)
        if getattr(self, 'iterative', False):
            v0 = self.lie_iter(Y, X)
        else:
            Xs = jordan_s(X)
            assert is_zero_mat(self.bpart(Xs) - Y)
            v0 = self.solve_conj(Y, Xs)
        return v0, Y, y, X

    def solve_conj(self, A, B):
        """v in U_P (v - I strictly block upper) with v A = B v; RREF particular solution."""
        d = self.d
        unk = [(r, c) for r in range(d) for c in range(d) if self.in_uP(r, c)]
        idx = {rc: i for i, rc in enumerate(unk)}
        rows, rhs = [], []
        # (I+N) A - B (I+N) = 0  ->  N A - B N = B - A
        for r in range(d):
            for c in range(d):
                row = [ZERO] * len(unk)
                for k in range(d):
                    if (r, k) in idx:
                        row[idx[(r, k)]] += A[k, c]
                    if (k, c) in idx:
                        row[idx[(k, c)]] -= B[r, k]
                rows.append(row); rhs.append(B[r, c] - A[r, c])
        Am = flint.fmpq_mat(len(rows), len(unk), [x for row in rows for x in row])
        sol = solve_particular(Am, rhs)
        assert sol is not None, "conjugation system inconsistent"
        v = eye(d)
        for (r, c), x in zip(unk, sol):
            v[r, c] = x
        return v


    # ---- Jordan-free iterations used in the proof (Lemma "iter" of section_claude.tex)
    def group_iter(self, h, g):
        """u in U_P with u^{-1} g u in h C_{U_P}(h)  (h = b(g) semisimple); then g_s = u h u^{-1}."""
        d = self.d
        u = eye(d)
        hi = h.inv()
        for t in range(1, self.S.m):
            R = mlog(hi * u.inv() * g * u)
            Rt = zeros(d, d)
            for r in range(d):
                for c in range(d):
                    if self.blk[c] - self.blk[r] == t:
                        Rt[r, c] = R[r, c]
            # split Rt = ker(Ad h - 1) + im(Ad h - 1); solve (1 - Ad(h^{-1})) Z = -Rt_im
            basis = [(r, c) for r in range(d) for c in range(d) if self.blk[c] - self.blk[r] == t]
            if not basis:
                continue
            n = len(basis)
            def coords(X):
                return [X[r, c] for (r, c) in basis]
            Acols = []
            for (r, c) in basis:
                E = zeros(d, d); E[r, c] = ONE
                Acols.append(coords(E - hi * E * h))
            A = flint.fmpq_mat(n, n, [Acols[j][i] for i in range(n) for j in range(n)])
            # Rt = k + A z with k in ker A (A semisimple): solve A z = Rt mod ker A
            K = nullspace(A)
            # augmented system [A | K] (z, kc) = Rt
            cols = Acols + K
            M = flint.fmpq_mat(n, len(cols), [cols[j][i] for i in range(n) for j in range(len(cols))])
            sol = solve_particular(M, coords(Rt))
            assert sol is not None
            Z = zeros(d, d)
            for (r, c), x in zip(basis, sol[:n]):
                Z[r, c] = -x
            u = u * mexp(Z)
        R = mlog(hi * u.inv() * g * u)
        assert is_zero_mat(h * R - R * h), "group iteration failed"
        return u

    def lie_iter(self, Y, X):
        """u in U_P with Ad(u^{-1}) X in Y + C_{u_P}(Y) (Y diagonal regular in weight basis)."""
        d = self.d
        u = eye(d)
        for t in range(1, self.S.m):
            R = u.inv() * X * u - Y
            Z = zeros(d, d)
            for r in range(d):
                for c in range(d):
                    if self.blk[c] - self.blk[r] == t and Y[r, r] != Y[c, c]:
                        Z[r, c] = R[r, c] / (Y[c, c] - Y[r, r])
            u = u * mexp(Z)
        R = u.inv() * X * u - Y
        assert is_zero_mat(R * Y - Y * R), "Lie iteration failed"
        return u

    # ---- (Z1)
    def split_nonzero(self, w):
        """w in U_P: return y in u_P^{!=0} with exp(-y) w in Z = C_{U_P}(S)."""
        d = self.d
        y = zeros(d, d)
        for t in range(1, self.S.m):
            R = mlog(mexp(-y) * w)
            delta = zeros(d, d)
            for r in range(d):
                for c in range(d):
                    if self.blk[c] - self.blk[r] == t and self.lab[r] != self.lab[c]:
                        delta[r, c] = R[r, c]
            y = y + delta
        z = mexp(-y) * w
        for r in range(d):
            for c in range(d):
                if r != c and self.lab[r] != self.lab[c]:
                    assert z[r, c] == 0
        return y

    def run(self, L, check_gt=True):
        t0 = time.time()
        d = self.d
        LieS, per = self.lieS_from_words(L)
        res = dict(d=d, m=self.S.m, nlab=self.nlab, dimLieS_short=LieS.dim)
        if check_gt:
            LieS_gt, order = self.lieS_groundtruth()
            res['dimLieS_gt'] = LieS_gt.dim
            res['T1_ok'] = (LieS == LieS_gt)
        if LieS.dim == 0:
            v0 = eye(d); Y = zeros(d, d); y = [ZERO] * self.nlab
        else:
            v0, Y, y, X = self.torus_conjugator(per, LieS)
        v0i = v0.inv()
        M = [v0i * g * v0 for g in self.M]
        res['bits_v0'] = mat_bits(v0)
        # check S in G' : Y must be the b-image ... (checked via ground truth below)
        xh, ms = [], []
        for g, bb in zip(M, self.b):
            Ya = bb * Y * bb.inv()
            wv = self.solve_conj(Ya, g * Y * g.inv())
            yv = self.split_nonzero(wv)
            xh.append(yv)
            ms.append(mexp(-yv) * g)
        res['bits_xhat'] = maxbits(xh); res['bits_m'] = maxbits(ms)
        # (Z2) Schreier generators of kernel of the conjugation action of b on C(S)
        CS = [(r, c) for r in range(d) for c in range(d) if self.lab[r] == self.lab[c]]
        acts = []
        for bb in self.b:
            bi = bb.inv()
            colsA = []
            for (r, c) in CS:
                E = zeros(d, d); E[r, c] = ONE
                F = bb * E * bi
                colsA.append([F[rr, cc] for (rr, cc) in CS])
                assert all(F[rr, cc] == 0 for rr in range(d) for cc in range(d)
                           if self.lab[rr] != self.lab[cc])
            n = len(CS)
            acts.append(flint.fmpq_mat(n, n, [colsA[j][i] for i in range(n) for j in range(n)]))
        sg, order = schreier(acts, ms)
        res['|Psi|'] = order
        seeds = []
        maxb_phi = 0
        for s in sg:
            bs = self.bpart(s)
            phi = bs.inv() * s
            assert is_zero_mat(self.bpart(phi) - eye(d))
            maxb_phi = max(maxb_phi, mat_bits(phi))
            seeds.append(mlog(phi))
        res['bits_phi'] = maxb_phi
        # (Z3) closure under Ad(m_a)^{+-1} and ad(Lie S), then Lie closure
        lieS_mats = [self.diag_of_labels(b) for b in LieS.basis]
        n_sp = self.closure(xh + seeds, ms, lieS_mats)
        res['dimU_new'] = n_sp.dim
        res['ht_u_new'] = subspace_bits(n_sp)
        res['time'] = round(time.time() - t0, 2)
        if check_gt:
            Sgt, _ = gt_general(self.S, self.info['_B'])
            T = self.Qw * v0       # adapted = T * ours * T^{-1}
            Ti = T.inv()
            gt_ours = Subspace([vec(Ti * unvec(b, d, d) * T) for b in Sgt.basis], d * d)
            res['dimU_gt'] = gt_ours.dim
            res['Z3_ok'] = (gt_ours == n_sp)
            res['xhat_in_U'] = all(gt_ours.contains(vec(x)) for x in xh)
            res['ht_u_gt_adapted'] = subspace_bits(Sgt)
        return res

    def closure(self, seeds, ms, lieS_mats):
        d = self.d
        ops = [(m, m.inv()) for m in ms]
        Sp = Subspace([], d * d)
        mats = []
        queue = [X for X in seeds if not is_zero_mat(X)]
        while queue:
            X = queue.pop()
            if Sp.contains(vec(X)):
                continue
            Sp = Sp.add([vec(X)])
            for Z in mats:
                queue.append(X * Z - Z * X)
            mats.append(X)
            for m, mi in ops:
                queue.append(m * X * mi); queue.append(mi * X * m)
            for Yd in lieS_mats:
                queue.append(Yd * X - X * Yd)
        return Sp


