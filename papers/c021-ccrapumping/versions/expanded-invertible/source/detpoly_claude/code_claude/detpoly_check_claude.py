# Exact check of the construction of section_claude.tex (detpoly_claude):
# polynomial-size spanning set of Lie(R_u G) under condition (a).
#   (T1) Lie(S), S = H^o, is the sum of Lie(closure<b(M_w)>^o) over short words w;
#   (T2-T5) regular semisimple X in Lie(G^o), torus conjugator v0 with v0 S v0^{-1} in G^o;
#   (Z1) xhat_a in exp(u_P^{!=0}) with xhat S xhat^{-1} = M_a S M_a^{-1};  xhat_a in U;
#   (Z2) U'' = R_u(closure<S, m_a>), m_a = xhat_a^{-1} M_a, via Schreier generators of the
#        kernel of the (finite) conjugation action of b(Gamma) on C(S);
#   (Z3) Lie U = Lie algebra generated by the (ad Lie S, Ad m_a)-closure of log xhat_a, Lie U''.
# Ground truth: gt_general of polytime_claude (Schreier generators of the kernel of the finite
# action on B = M_d^{H^o}).   Run:  python3 -I detpoly_check_claude.py FAMILY SEED N
